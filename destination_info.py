def get_destination_info(country_name):
    return DESTINATION_INFO.get(
        country_name,
        {
            "famous_for": [],
            "foods": [],
            "events": [],
            "places": [],
        },
    )


def print_section(title, items):
    print(f"\n{title}")

    if not items:
        print("  No information available.")
        return

    for item in items:
        print(f"  • {item}")


def show_destination_info(country_name, section=None):
    info = get_destination_info(country_name)

    print("\n" + "=" * 60)
    print(f"🌍 {country_name}")
    print("=" * 60)

    if section == "foods":
        print_section("🍣 Famous Foods", info["foods"])

    elif section == "events":
        print_section("🎉 Events & Experiences", info["events"])

    elif section == "places":
        print_section("🏯 Famous Places", info["places"])

    else:
        print_section(
            "✨ Famous For",
            info["famous_for"],
        )

        print_section(
            "🍣 Famous Foods",
            info["foods"],
        )

        print_section(
            "🎉 Events & Experiences",
            info["events"],
        )

        print_section(
            "🏯 Famous Places",
            info["places"],
        )