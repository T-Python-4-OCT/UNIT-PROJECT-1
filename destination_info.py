def get_destination_info(country_name):
    return DESTINATION_INFO.get(
        country_name,
        {
            "capital": "N/A",
            "language": "N/A",
            "population": "N/A",
            "continent": "N/A",
            "famous_for": [],
            "foods": [],
            "cities": {}
        }
    )


def print_section(title, items):
    print(f"\n{title}")

    if not items:
        print("  No information available.")
        return

    for item in items:
        print(f"  • {item}")


def get_city_info(country_name, city_name):
    country_info = get_destination_info(country_name)
    cities = country_info.get("cities", {})

    return cities.get(
        city_name,
        {
            "places": [],
            "events": []
        }
    )


